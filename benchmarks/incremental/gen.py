"""Writes a deterministic NEXUL program of about N lines (ADR 0016, validation §3).

usage: python -I gen.py <out.nx> [functions=1000] [variant=0]

Each function `g<i>` is reachable from `main`, does arithmetic on integers, a `Vec` and a
`String`, and calls `g<i-1>`. `variant` changes only the body of `g<N/2>`: rebuilding
after it measures a one-body modification.
"""
import sys

out = sys.argv[1]
n = int(sys.argv[2]) if len(sys.argv) > 2 else 1000
variant = int(sys.argv[3]) if len(sys.argv) > 3 else 0
lines = ["// edition: 1", "// Generated by benchmarks/incremental/gen.py. Do not edit.", ""]
for i in range(n):
    k = 7 + (variant if i == n // 2 else 0)
    prev = f"g{i - 1}(x + 1)" if i else "x"
    lines += [
        f"fn i64 g{i}(i64 x) {{",
        f"    var Vec[i64] v = Vec.new()",
        f"    var i64 j = 0",
        f"    while j < {k} {{",
        f"        v.push(x * j + {i})",
        f"        j += 1",
        f"    }}",
        f"    var i64 s = 0",
        f"    for e in v {{",
        f"        s += e % {i + 3}",
        f"    }}",
        f"    let name = \"f{i}:{{s}}\"",
        f"    if name.len() > 100 {{",
        f"        return 0",
        f"    }}",
        f"    if x > {i} {{",
        f"        return s",
        f"    }}",
        f"    return s + {prev}",
        f"}}",
        "",
    ]
lines += ["fn main() {", f"    println(\"{{g{n - 1}(0)}}\")", "}", ""]
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
