//! Portable C11 backend: monomorphization of the NIR and C emission (spec §10.1).

use nxc_nir::build::param_by_ref;
use nxc_nir::nir::*;
use nxc_sema::defs::{AdtKind, ConstValue, FnId, FnKind, Program};
use nxc_sema::thir::PrimOp;
use nxc_sema::ty::{FloatTy, IntTy, Ty, TyKind};
use nxc_syntax::ast::{BinOp, Convention, UnOp};
use nxc_syntax::token::{Align, FormatKind, FormatSpec};
use nxc_syntax::{SourceMap, Span};
use std::collections::{HashMap, HashSet};
use std::fmt::Write;

pub const RUNTIME: &str = include_str!("../../../runtime/nexul_rt.h");

pub enum Entry {
    Main(FnId),
    Tests(Vec<FnId>),
}

pub struct Options {
    /// Emit `#line` directives pointing at the NEXUL sources.
    pub line_directives: bool,
}

impl Default for Options {
    fn default() -> Self {
        Options { line_directives: true }
    }
}

/// The C structures of the program, identified by NEXUL type (or enum payload).
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
enum CItem {
    Ty(Ty),
    Payload(Ty, u32),
}

struct Gen<'a> {
    p: &'a Program,
    sm: &'a SourceMap,
    bodies: &'a HashMap<FnId, Body>,
    opts: &'a Options,
    names: HashMap<CItem, String>,
    forward: String,
    defs: String,
    defined: HashSet<CItem>,
    defining: HashSet<CItem>,
    pending_payloads: Vec<CItem>,
    fnptr_typedefs: String,
    drop_names: HashMap<Ty, String>,
    drop_queue: Vec<Ty>,
    drop_protos: String,
    drop_defs: String,
    instances: HashMap<(FnId, Vec<Ty>), String>,
    fn_queue: Vec<(FnId, Vec<Ty>)>,
    protos: String,
    fn_defs: String,
    externs: HashMap<FnId, String>,
    extern_decls: String,
    strings: HashMap<Vec<u8>, String>,
    string_decls: String,
    locs: HashMap<(String, usize, usize), String>,
    loc_decls: String,
    specs: HashMap<String, String>,
    spec_decls: String,
    counter: usize,
    links: Vec<String>,
    /// The function being emitted is `@track_caller`: panics use `nx_caller`.
    in_track_caller: bool,
}

/// Generates the complete C translation unit.
pub fn generate(p: &Program, sm: &SourceMap, bodies: &HashMap<FnId, Body>, entry: &Entry, opts: &Options) -> (String, Vec<String>) {
    let mut g = Gen {
        p,
        sm,
        bodies,
        opts,
        names: HashMap::new(),
        forward: String::new(),
        defs: String::new(),
        defined: HashSet::new(),
        defining: HashSet::new(),
        pending_payloads: Vec::new(),
        fnptr_typedefs: String::new(),
        drop_names: HashMap::new(),
        drop_queue: Vec::new(),
        drop_protos: String::new(),
        drop_defs: String::new(),
        instances: HashMap::new(),
        fn_queue: Vec::new(),
        protos: String::new(),
        fn_defs: String::new(),
        externs: HashMap::new(),
        extern_decls: String::new(),
        strings: HashMap::new(),
        string_decls: String::new(),
        locs: HashMap::new(),
        loc_decls: String::new(),
        specs: HashMap::new(),
        spec_decls: String::new(),
        counter: 0,
        links: Vec::new(),
        in_track_caller: false,
    };
    let mut main = String::new();
    match entry {
        Entry::Main(f) => {
            let name = g.instance(*f, vec![]);
            main.push_str(&format!(
                "int main(int argc, char** argv) {{\n    nx_rt_init(argc, argv);\n    {}();\n    nx_exit(0);\n}}\n",
                name
            ));
        }
        Entry::Tests(tests) => {
            let mut cases = String::new();
            for (i, t) in tests.iter().enumerate() {
                let name = g.instance(*t, vec![]);
                cases.push_str(&format!("    case {}: {}(); break;\n", i, name));
            }
            main.push_str(&format!(
                "int main(int argc, char** argv) {{\n    nx_rt_init(argc, argv);\n    int which = argc > 1 ? atoi(argv[1]) : -1;\n    switch (which) {{\n{}    default: return 2;\n    }}\n    nx_exit(0);\n}}\n",
                cases
            ));
        }
    }
    // Generate every reachable function and drop glue (they discover more work).
    loop {
        if let Some((f, targs)) = g.fn_queue.pop() {
            g.emit_fn(f, &targs);
            continue;
        }
        if let Some(t) = g.drop_queue.pop() {
            g.emit_drop_glue(t);
            continue;
        }
        if let Some(item) = g.pending_payloads.pop() {
            g.ensure_def(item);
            continue;
        }
        break;
    }
    let mut out = String::new();
    out.push_str("/* Generated by nxc, the NEXUL compiler. Do not edit. */\n");
    out.push_str(RUNTIME);
    out.push_str("\n/* ---- program types ---- */\n");
    out.push_str(&g.forward);
    out.push_str(&g.fnptr_typedefs);
    out.push_str(&g.defs);
    out.push_str("\n/* ---- constants ---- */\n");
    out.push_str(&g.string_decls);
    out.push_str(&g.loc_decls);
    out.push_str(&g.spec_decls);
    out.push_str("\n/* ---- external functions ---- */\n");
    out.push_str(&g.extern_decls);
    out.push_str("\n/* ---- prototypes ---- */\n");
    out.push_str(&g.drop_protos);
    out.push_str(&g.protos);
    out.push_str("\n/* ---- drop glue ---- */\n");
    out.push_str(&g.drop_defs);
    out.push_str("\n/* ---- functions ---- */\n");
    out.push_str(&g.fn_defs);
    out.push('\n');
    out.push_str(&main);
    (out, g.links)
}

fn sanitize(s: &str) -> String {
    let mut o: String = s.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect();
    while o.contains("__") {
        o = o.replace("__", "_");
    }
    let o = o.trim_matches('_').to_string();
    if o.len() > 40 {
        o[..40].to_string()
    } else {
        o
    }
}

fn c_string_literal(bytes: &[u8]) -> String {
    let mut s = String::from("\"");
    for &b in bytes {
        if (b.is_ascii_alphanumeric() || b" .,:;!#$%&'()*+-/<=>@[]^_`{|}~".contains(&b)) && b != b'?' {
            s.push(b as char);
        } else {
            s.push_str(&format!("\\{:03o}", b));
        }
    }
    s.push('"');
    s
}

fn int_cty(i: IntTy) -> &'static str {
    match i {
        IntTy::I8 => "int8_t",
        IntTy::I16 => "int16_t",
        IntTy::I32 => "int32_t",
        IntTy::I64 => "int64_t",
        IntTy::Isize => "intptr_t",
        IntTy::U8 => "uint8_t",
        IntTy::U16 => "uint16_t",
        IntTy::U32 => "uint32_t",
        IntTy::U64 => "uint64_t",
        IntTy::Usize => "uintptr_t",
    }
}

fn int_suffix(i: IntTy) -> &'static str {
    i.name()
}

/// Bits of an integer type for range checks of conversions (isize/usize: 64).
fn int_bits(i: IntTy) -> u32 {
    i.bits()
}

impl<'a> Gen<'a> {
    fn fresh(&mut self) -> usize {
        self.counter += 1;
        self.counter
    }

    fn tcx(&self) -> &'a nxc_sema::ty::TyCtx {
        &self.p.tcx
    }

    // -----------------------------------------------------------------------
    // Types

    fn ctype(&mut self, t: Ty) -> String {
        let tcx = self.tcx();
        match &*tcx.kind(t) {
            TyKind::Int(i) => int_cty(*i).into(),
            TyKind::Float(FloatTy::F32) => "float".into(),
            TyKind::Float(FloatTy::F64) => "double".into(),
            TyKind::Bool => "bool".into(),
            TyKind::Char => "uint32_t".into(),
            TyKind::Unit | TyKind::Never | TyKind::Error => "nx_unit".into(),
            TyKind::Ptr(e) => format!("{}*", self.ctype_shallow(*e)),
            TyKind::Fn(params, ret) => {
                let key = CItem::Ty(t);
                if let Some(n) = self.names.get(&key) {
                    return n.clone();
                }
                let n = format!("nx_fn{}", self.fresh());
                self.names.insert(key, n.clone());
                let ret_c = if self.is_void(*ret) { "void".to_string() } else { self.ctype(*ret) };
                let ps: Vec<String> = params
                    .iter()
                    .map(|&(c, pt)| {
                        let base = self.ctype(pt);
                        if param_by_ref(self.p, c, pt) {
                            format!("{}*", base)
                        } else {
                            base
                        }
                    })
                    .collect();
                let ps = if ps.is_empty() { "void".to_string() } else { ps.join(", ") };
                let _ = writeln!(self.fnptr_typedefs, "typedef {} (*{})({});", ret_c, n, ps);
                n
            }
            TyKind::Adt(id, _) if Some(*id) == self.p.lang.string => "nx_String".into(),
            TyKind::Param(_) | TyKind::Infer(_) | TyKind::IntVar(_) | TyKind::FloatVar(_) => {
                panic!("internal: non-concrete type in code generation: {}", self.p.ty_str(t))
            }
            TyKind::Tuple(_) | TyKind::Array(..) | TyKind::Adt(..) => {
                let n = self.struct_name(CItem::Ty(t));
                self.ensure_def(CItem::Ty(t));
                n
            }
        }
    }

    /// The C name of a type used behind a pointer: a forward declaration is enough, so
    /// the definition is only scheduled (this breaks cycles of recursive types).
    fn ctype_shallow(&mut self, t: Ty) -> String {
        let tcx = self.tcx();
        match &*tcx.kind(t) {
            TyKind::Adt(id, _) if Some(*id) == self.p.lang.string => "nx_String".into(),
            TyKind::Tuple(_) | TyKind::Array(..) | TyKind::Adt(..) => {
                let n = self.struct_name(CItem::Ty(t));
                if !self.defined.contains(&CItem::Ty(t)) {
                    self.pending_payloads.push(CItem::Ty(t));
                }
                n
            }
            _ => self.ctype(t),
        }
    }

    fn is_void(&self, t: Ty) -> bool {
        let tcx = self.tcx();
        t == tcx.unit || t == tcx.never
    }

    fn struct_name(&mut self, item: CItem) -> String {
        if let Some(n) = self.names.get(&item) {
            return n.clone();
        }
        let base = match item {
            CItem::Ty(t) => self.p.ty_str(t),
            CItem::Payload(t, v) => format!("{}_v{}", self.p.ty_str(t), v),
        };
        let n = format!("nx_{}_{}", sanitize(&base), self.fresh());
        let _ = writeln!(self.forward, "typedef struct {} {};", n, n);
        self.names.insert(item, n.clone());
        n
    }

    /// Emits the definition of a structure after the definitions it needs by value.
    fn ensure_def(&mut self, item: CItem) {
        if self.defined.contains(&item) || self.defining.contains(&item) {
            return;
        }
        let tcx = self.tcx();
        self.defining.insert(item);
        let name = self.struct_name(item);
        let mut body = String::new();
        match item {
            CItem::Payload(t, v) => {
                let (id, args) = tcx.as_adt(t).unwrap();
                let fields: Vec<Ty> = self.p.adt(id).variants()[v as usize].fields.iter().map(|&f| tcx.subst(f, &args)).collect();
                for (i, f) in fields.iter().enumerate() {
                    let ct = self.ctype(*f);
                    let _ = writeln!(body, "    {} f{};", ct, i);
                }
                if fields.is_empty() {
                    body.push_str("    uint8_t _unused;\n");
                }
            }
            CItem::Ty(t) => match &*tcx.kind(t) {
                TyKind::Tuple(elems) => {
                    for (i, e) in elems.iter().enumerate() {
                        let ct = self.ctype(*e);
                        let _ = writeln!(body, "    {} f{};", ct, i);
                    }
                }
                TyKind::Array(e, n) => {
                    if *n == 0 {
                        body.push_str("    uint8_t _unused;\n");
                    } else {
                        let ct = self.ctype(*e);
                        let _ = writeln!(body, "    {} a[{}];", ct, n);
                    }
                }
                TyKind::Adt(id, args) => {
                    let adt = self.p.adt(*id);
                    match &adt.kind {
                        AdtKind::Struct { fields } => {
                            for f in fields {
                                let ft = tcx.subst(f.ty, args);
                                let ct = if f.indirect { self.ctype_shallow(ft) } else { self.ctype(ft) };
                                if f.indirect {
                                    let _ = writeln!(body, "    {}* f_{};", ct, f.name);
                                } else {
                                    let _ = writeln!(body, "    {} f_{};", ct, f.name);
                                }
                            }
                            if fields.is_empty() {
                                body.push_str("    uint8_t _unused;\n");
                            }
                        }
                        AdtKind::Enum { variants } => {
                            body.push_str("    uint32_t tag;\n");
                            let with_fields: Vec<(usize, bool)> = variants.iter().enumerate().filter(|(_, v)| !v.fields.is_empty()).map(|(i, v)| (i, v.indirect)).collect();
                            if !with_fields.is_empty() {
                                body.push_str("    union {\n");
                                for (i, indirect) in with_fields {
                                    let pn = self.struct_name(CItem::Payload(t, i as u32));
                                    if indirect {
                                        let _ = writeln!(body, "        {}* v{};", pn, i);
                                        self.pending_payloads.push(CItem::Payload(t, i as u32));
                                    } else {
                                        self.ensure_def(CItem::Payload(t, i as u32));
                                        let _ = writeln!(body, "        {} v{};", pn, i);
                                    }
                                }
                                body.push_str("    } u;\n");
                            }
                        }
                    }
                }
                _ => {}
            },
        }
        let _ = write!(self.defs, "struct {} {{\n{}}};\n", name, body);
        self.defining.remove(&item);
        self.defined.insert(item);
    }

    // -----------------------------------------------------------------------
    // Drop glue

    fn drop_fn(&mut self, t: Ty) -> Option<String> {
        if !self.p.needs_drop(t) {
            return None;
        }
        if let Some(n) = self.drop_names.get(&t) {
            return Some(n.clone());
        }
        let n = format!("nx_drop_{}_{}", sanitize(&self.p.ty_str(t)), self.fresh());
        self.drop_names.insert(t, n.clone());
        let ct = self.ctype(t);
        let _ = writeln!(self.drop_protos, "static void {}({}* p);", n, ct);
        self.drop_queue.push(t);
        Some(n)
    }

    fn emit_drop_glue(&mut self, t: Ty) {
        let tcx = self.tcx();
        let name = self.drop_names[&t].clone();
        let ct = self.ctype(t);
        let mut b = String::new();
        match &*tcx.kind(t) {
            TyKind::Tuple(elems) => {
                for (i, e) in elems.clone().iter().enumerate() {
                    if let Some(d) = self.drop_fn(*e) {
                        let _ = writeln!(b, "    {}(&p->f{});", d, i);
                    }
                }
            }
            TyKind::Array(e, n) => {
                if let Some(d) = self.drop_fn(*e) {
                    let _ = writeln!(b, "    for (size_t i = 0; i < {}; i++) {}(&p->a[i]);", n, d);
                }
            }
            TyKind::Adt(id, args) => {
                let adt = self.p.adt(*id);
                if let Some(df) = adt.drop_fn {
                    let inst = self.instance(df, args.clone());
                    let _ = writeln!(b, "    {}(p);", inst);
                }
                match &adt.kind {
                    AdtKind::Struct { fields } => {
                        for f in fields {
                            let ft = tcx.subst(f.ty, args);
                            let d = self.drop_fn(ft);
                            if f.indirect {
                                if let Some(d) = d {
                                    let _ = writeln!(b, "    {}(p->f_{});", d, f.name);
                                }
                                let _ = writeln!(b, "    nx_free(p->f_{});", f.name);
                            } else if let Some(d) = d {
                                let _ = writeln!(b, "    {}(&p->f_{});", d, f.name);
                            }
                        }
                    }
                    AdtKind::Enum { variants } => {
                        let _ = writeln!(b, "    switch (p->tag) {{");
                        for (vi, v) in variants.iter().enumerate() {
                            if v.fields.is_empty() {
                                continue;
                            }
                            let mut case = String::new();
                            for (fi, &f) in v.fields.iter().enumerate() {
                                let ft = tcx.subst(f, args);
                                if let Some(d) = self.drop_fn(ft) {
                                    if v.indirect {
                                        let _ = writeln!(case, "        {}(&p->u.v{}->f{});", d, vi, fi);
                                    } else {
                                        let _ = writeln!(case, "        {}(&p->u.v{}.f{});", d, vi, fi);
                                    }
                                }
                            }
                            if v.indirect {
                                let _ = writeln!(case, "        nx_free(p->u.v{});", vi);
                            }
                            if !case.is_empty() {
                                let _ = write!(b, "    case {}:\n{}        break;\n", vi, case);
                            }
                        }
                        b.push_str("    default: break;\n    }\n");
                    }
                }
            }
            _ => {}
        }
        let _ = write!(self.drop_defs, "static void {}({}* p) {{\n{}}}\n", name, ct, b);
    }

    // -----------------------------------------------------------------------
    // Functions

    fn instance(&mut self, f: FnId, targs: Vec<Ty>) -> String {
        let key = (f, targs);
        if let Some(n) = self.instances.get(&key) {
            return n.clone();
        }
        let fd = self.p.func(f);
        let mut label = fd.qualified_name(self.p);
        if !key.1.is_empty() {
            let a: Vec<String> = key.1.iter().map(|&t| self.p.ty_str(t)).collect();
            label = format!("{}[{}]", label, a.join(", "));
        }
        let n = format!("nxf_{}_{}", sanitize(&label), self.fresh());
        self.instances.insert(key.clone(), n.clone());
        self.fn_queue.push(key);
        n
    }

    fn extern_name(&mut self, f: FnId) -> String {
        if let Some(n) = self.externs.get(&f) {
            return n.clone();
        }
        let fd = self.p.func(f);
        let n = format!("nx_ext_{}", fd.name);
        let ret = if self.is_void(fd.ret) { "void".to_string() } else { self.ctype(fd.ret) };
        let params: Vec<String> = fd.params.iter().map(|p| p.ty).collect::<Vec<_>>().into_iter().map(|t| self.ctype(t)).collect();
        let ps = if params.is_empty() { "void".to_string() } else { params.join(", ") };
        let _ = writeln!(self.extern_decls, "extern {} {}({}) NX_SYM(\"{}\");", ret, n, ps, fd.name);
        if let FnKind::Extern { link: Some(l), .. } = &fd.kind {
            if !self.links.contains(l) {
                self.links.push(l.clone());
            }
        }
        self.externs.insert(f, n.clone());
        n
    }

    fn emit_fn(&mut self, f: FnId, targs: &[Ty]) {
        let name = self.instances[&(f, targs.to_vec())].clone();
        let Some(body) = self.bodies.get(&f) else {
            panic!("internal: no body for {}", self.p.func(f).name);
        };
        let tcx = self.tcx();
        let local_tys: Vec<Ty> = body.locals.iter().map(|l| tcx.subst(l.ty, targs)).collect();
        let ret_ty = local_tys[0];
        let ret_c = if self.is_void(ret_ty) { "void".to_string() } else { self.ctype(ret_ty) };
        let mut params = Vec::new();
        for i in 1..=body.arg_count {
            let ct = self.ctype(local_tys[i]);
            params.push(format!("{} _{}", ct, i));
        }
        let track_caller = self.p.func(f).track_caller;
        if track_caller {
            params.push("const nx_loc* nx_caller".to_string());
        }
        let ps = if params.is_empty() { "void".to_string() } else { params.join(", ") };
        let sig = format!("static {} {}({})", ret_c, name, ps);
        self.in_track_caller = track_caller;
        let _ = writeln!(self.protos, "{};", sig);
        let mut cx = FnCx { targs: targs.to_vec(), local_tys, out: String::new(), last_line: None, ret_void: self.is_void(ret_ty) };
        let mut decls = String::new();
        for (i, l) in body.locals.iter().enumerate().skip(body.arg_count + 1) {
            let ct = self.ctype(cx.local_tys[i]);
            let comment = l.name.as_ref().map(|n| format!(" /* {} */", n)).unwrap_or_default();
            let _ = writeln!(decls, "    {} _{};{}", ct, i, comment);
        }
        if !cx.ret_void {
            let ct = self.ctype(cx.local_tys[0]);
            let _ = writeln!(decls, "    {} _0;", ct);
        }
        for (bi, b) in body.blocks.iter().enumerate() {
            let _ = writeln!(cx.out, "bb{}:;", bi);
            for s in &b.stmts {
                self.emit_stmt(&mut cx, s);
            }
            self.emit_term(&mut cx, b);
        }
        let fd = self.p.func(f);
        let _ = write!(self.fn_defs, "/* {} */\n{} {{\n{}{}}}\n\n", fd.qualified_name(self.p), sig, decls, cx.out);
    }

    // -----------------------------------------------------------------------
    // Locations, strings, specs

    fn loc(&mut self, span: Span) -> String {
        if self.in_track_caller {
            return "nx_caller".into();
        }
        if span.is_dummy() {
            return "NULL".into();
        }
        let l = self.sm.location(span);
        let key = (l.file.to_string(), l.line, l.col);
        if let Some(n) = self.locs.get(&key) {
            return format!("&{}", n);
        }
        let n = format!("nx_loc{}", self.fresh());
        let _ = writeln!(self.loc_decls, "static const nx_loc {} = {{{}, {}, {}}};", n, c_string_literal(key.0.as_bytes()), key.1, key.2);
        self.locs.insert(key, n.clone());
        format!("&{}", n)
    }

    fn string_const(&mut self, s: &[u8]) -> String {
        let name = match self.strings.get(s) {
            Some(n) => n.clone(),
            None => {
                let n = format!("nx_str{}", self.fresh());
                let _ = writeln!(self.string_decls, "static const char {}[] = {};", n, c_string_literal(s));
                self.strings.insert(s.to_vec(), n.clone());
                n
            }
        };
        format!("nx_str_lit({}, {})", name, s.len())
    }

    fn spec(&mut self, spec: &Option<FormatSpec>) -> String {
        let Some(sp) = spec else { return "NULL".into() };
        let align = match sp.align {
            None => 0,
            Some(Align::Left) => 1,
            Some(Align::Center) => 2,
            Some(Align::Right) => 3,
        };
        let kind = match sp.kind {
            None => 0,
            Some(FormatKind::LowerHex) => 1,
            Some(FormatKind::UpperHex) => 2,
            Some(FormatKind::Octal) => 3,
            Some(FormatKind::Binary) => 4,
            Some(FormatKind::Exponent) => 5,
        };
        let init = format!(
            "{{{}, {}, {}, {}, {}, {}, {}}}",
            sp.fill as u32,
            align,
            sp.plus,
            sp.zero,
            sp.width.map(|w| w as i64).unwrap_or(-1),
            sp.precision.map(|w| w as i64).unwrap_or(-1),
            kind
        );
        if let Some(n) = self.specs.get(&init) {
            return format!("&{}", n);
        }
        let n = format!("nx_spec{}", self.fresh());
        let _ = writeln!(self.spec_decls, "static const nx_spec {} = {};", n, init);
        self.specs.insert(init, n.clone());
        format!("&{}", n)
    }

    // -----------------------------------------------------------------------
    // Places and operands

    fn place_ty(&self, cx: &FnCx, place: &Place) -> Ty {
        let tcx = self.tcx();
        let mut t = cx.local_tys[place.local as usize];
        for pr in &place.proj {
            t = match (pr, &*tcx.kind(t)) {
                (Proj::Deref, TyKind::Ptr(e)) => *e,
                (Proj::Field(i), TyKind::Tuple(ts)) => ts[*i as usize],
                (Proj::Field(i), TyKind::Adt(id, args)) => tcx.subst(self.p.adt(*id).fields()[*i as usize].ty, args),
                (Proj::VariantField(v, i), TyKind::Adt(id, args)) => tcx.subst(self.p.adt(*id).variants()[*v as usize].fields[*i as usize], args),
                (Proj::Index(_), TyKind::Array(e, _)) => *e,
                _ => panic!("internal: bad projection {:?} on {}", pr, self.p.ty_str(t)),
            };
        }
        t
    }

    fn place(&self, cx: &FnCx, place: &Place) -> String {
        let tcx = self.tcx();
        let mut s = format!("_{}", place.local);
        let mut t = cx.local_tys[place.local as usize];
        for pr in &place.proj {
            match (pr, &*tcx.kind(t)) {
                (Proj::Deref, TyKind::Ptr(e)) => {
                    s = format!("(*{})", s);
                    t = *e;
                }
                (Proj::Field(i), TyKind::Tuple(ts)) => {
                    s = format!("{}.f{}", s, i);
                    t = ts[*i as usize];
                }
                (Proj::Field(i), TyKind::Adt(id, args)) => {
                    let f = &self.p.adt(*id).fields()[*i as usize];
                    s = if f.indirect { format!("(*{}.f_{})", s, f.name) } else { format!("{}.f_{}", s, f.name) };
                    t = tcx.subst(f.ty, args);
                }
                (Proj::VariantField(v, i), TyKind::Adt(id, args)) => {
                    let var = &self.p.adt(*id).variants()[*v as usize];
                    s = if var.indirect { format!("{}.u.v{}->f{}", s, v, i) } else { format!("{}.u.v{}.f{}", s, v, i) };
                    t = tcx.subst(var.fields[*i as usize], args);
                }
                (Proj::Index(l), TyKind::Array(e, _)) => {
                    s = format!("{}.a[_{}]", s, l);
                    t = *e;
                }
                _ => panic!("internal: bad projection"),
            }
        }
        s
    }

    fn operand_ty(&self, cx: &FnCx, o: &Operand) -> Ty {
        match o {
            Operand::Copy(p) | Operand::Move(p) => self.place_ty(cx, p),
            Operand::Const(_, t) => self.tcx().subst(*t, &cx.targs),
            Operand::FnRef(f) => {
                let fd = self.p.func(*f);
                let params = fd.params.iter().map(|p| (p.conv, p.ty)).collect();
                self.tcx().mk(TyKind::Fn(params, fd.ret))
            }
        }
    }

    fn operand(&mut self, cx: &FnCx, o: &Operand) -> String {
        match o {
            Operand::Copy(p) | Operand::Move(p) => self.place(cx, p),
            Operand::Const(v, t) => {
                let t = self.tcx().subst(*t, &cx.targs);
                self.constant(v, t)
            }
            Operand::FnRef(f) => self.instance(*f, vec![]),
        }
    }

    fn constant(&mut self, v: &ConstValue, t: Ty) -> String {
        let tcx = self.tcx();
        match (v, &*tcx.kind(t)) {
            (ConstValue::Int(n), TyKind::Int(i)) => int_literal(*n, *i),
            (ConstValue::Int(n), TyKind::Float(f)) => float_literal(*n as f64, *f),
            (ConstValue::Float(x), TyKind::Float(f)) => float_literal(*x, *f),
            (ConstValue::Bool(b), _) => if *b { "true".into() } else { "false".into() },
            (ConstValue::Char(c), _) => format!("UINT32_C({})", *c as u32),
            (ConstValue::Str(s), _) => self.string_const(s.as_bytes()),
            (ConstValue::Unit, _) => "((nx_unit)0)".into(),
            (ConstValue::Int(n), TyKind::Char) => format!("UINT32_C({})", n),
            (ConstValue::Int(n), _) => format!("{}", n),
            (ConstValue::Float(x), _) => format!("{:?}", x),
        }
    }

    // -----------------------------------------------------------------------
    // Statements

    fn line(&mut self, cx: &mut FnCx, span: Span) {
        if !self.opts.line_directives || span.is_dummy() {
            return;
        }
        let l = self.sm.location(span);
        let key = (l.line, l.file.to_string());
        if cx.last_line.as_ref() != Some(&key) {
            let _ = writeln!(cx.out, "#line {} {}", l.line, c_string_literal(l.file.as_bytes()));
            cx.last_line = Some(key);
        }
    }

    fn emit_stmt(&mut self, cx: &mut FnCx, s: &Statement) {
        self.line(cx, s.span);
        match &s.kind {
            // A function returning `()` has no return slot in C.
            StmtKind::Assign(place, _) if place.local == RETURN && place.proj.is_empty() && cx.ret_void => {}
            StmtKind::Assign(place, rv) => self.emit_assign(cx, place, rv, s.span),
            StmtKind::Drop(place) => {
                let t = self.place_ty(cx, place);
                if let Some(d) = self.drop_fn(t) {
                    let p = self.place(cx, place);
                    let _ = writeln!(cx.out, "    {}(&{});", d, p);
                }
            }
            StmtKind::DropIfInit(l) => {
                // Not reached after drop elaboration; drop unconditionally as a fallback.
                let t = cx.local_tys[*l as usize];
                if let Some(d) = self.drop_fn(t) {
                    let _ = writeln!(cx.out, "    {}(&_{});", d, l);
                }
            }
            StmtKind::MarkMoved(_) | StmtKind::Nop => {}
            StmtKind::BoundsCheck { index, len, dest } => {
                let it = self.operand_ty(cx, index);
                let i = self.operand(cx, index);
                let n = self.operand(cx, len);
                let loc = self.loc(s.span);
                let signed = self.tcx().as_int(it).map_or(false, |i| i.signed());
                if signed {
                    let _ = writeln!(cx.out, "    _{} = nx_index_s((int64_t){}, (size_t){}, {});", dest, i, n, loc);
                } else {
                    let _ = writeln!(cx.out, "    _{} = nx_index_u((uint64_t){}, (size_t){}, {});", dest, i, n, loc);
                }
            }
            StmtKind::FreeBox(place, b) => {
                let p = self.place(cx, place);
                let t = self.place_ty(cx, place);
                match b {
                    BoxRef::Field(i) => {
                        let (id, _) = self.tcx().as_adt(t).unwrap();
                        let fname = self.p.adt(id).fields()[*i as usize].name.clone();
                        let _ = writeln!(cx.out, "    nx_free({}.f_{});", p, fname);
                    }
                    BoxRef::Variant(v) => {
                        let _ = writeln!(cx.out, "    nx_free({}.u.v{});", p, v);
                    }
                }
            }
        }
    }

    fn emit_assign(&mut self, cx: &mut FnCx, place: &Place, rv: &Rvalue, span: Span) {
        let tcx = self.tcx();
        let dst_ty = self.place_ty(cx, place);
        let dst = self.place(cx, place);
        match rv {
            Rvalue::Use(o) => {
                let v = self.operand(cx, o);
                let _ = writeln!(cx.out, "    {} = {};", dst, v);
            }
            Rvalue::Ref(p) => {
                let v = self.place(cx, p);
                let _ = writeln!(cx.out, "    {} = &{};", dst, v);
            }
            Rvalue::Discriminant(p) => {
                let v = self.place(cx, p);
                let _ = writeln!(cx.out, "    {} = (uint32_t){}.tag;", dst, v);
            }
            Rvalue::Unary(op, o) => {
                let t = self.operand_ty(cx, o);
                let v = self.operand(cx, o);
                let e = match (op, &*tcx.kind(t)) {
                    (UnOp::Not, _) => format!("!{}", v),
                    (UnOp::Neg, TyKind::Int(i)) => {
                        let loc = self.loc(span);
                        format!("nx_neg_{}({}, {})", int_suffix(*i), v, loc)
                    }
                    (UnOp::Neg, _) => format!("-{}", v),
                    (UnOp::BitNot, TyKind::Int(i)) => format!("({})~{}", int_cty(*i), v),
                    (UnOp::BitNot, _) => format!("~{}", v),
                };
                let _ = writeln!(cx.out, "    {} = {};", dst, e);
            }
            Rvalue::Binary(op, a, b) => {
                let t = self.operand_ty(cx, a);
                let bt = self.operand_ty(cx, b);
                let x = self.operand(cx, a);
                let y = self.operand(cx, b);
                let e = self.binary(*op, t, bt, &x, &y, span);
                let _ = writeln!(cx.out, "    {} = {};", dst, e);
            }
            Rvalue::Cast(o, to) => {
                let to = tcx.subst(*to, &cx.targs);
                let from = self.operand_ty(cx, o);
                let v = self.operand(cx, o);
                let e = self.cast(from, to, &v, span);
                let _ = writeln!(cx.out, "    {} = {};", dst, e);
            }
            Rvalue::Repeat(o, n) => {
                let v = self.operand(cx, o);
                if *n > 0 {
                    let _ = writeln!(cx.out, "    for (size_t i = 0; i < {}; i++) {}.a[i] = {};", n, dst, v);
                }
            }
            Rvalue::Aggregate(kind, ops) => {
                let vals: Vec<String> = ops.iter().map(|o| self.operand(cx, o)).collect();
                match kind {
                    AggKind::Tuple => {
                        for (i, v) in vals.iter().enumerate() {
                            let _ = writeln!(cx.out, "    {}.f{} = {};", dst, i, v);
                        }
                    }
                    AggKind::Array => {
                        for (i, v) in vals.iter().enumerate() {
                            let _ = writeln!(cx.out, "    {}.a[{}] = {};", dst, i, v);
                        }
                    }
                    AggKind::Adt { adt, variant, .. } => {
                        let a = self.p.adt(*adt);
                        let (_, args) = tcx.as_adt(dst_ty).unwrap_or((*adt, vec![]));
                        match variant {
                            None => {
                                for (f, v) in a.fields().iter().zip(vals.iter()) {
                                    if f.indirect {
                                        let ft = tcx.subst(f.ty, &args);
                                        let ct = self.ctype(ft);
                                        let _ = writeln!(cx.out, "    {}.f_{} = ({}*)nx_alloc(sizeof({}));", dst, f.name, ct, ct);
                                        let _ = writeln!(cx.out, "    *{}.f_{} = {};", dst, f.name, v);
                                    } else {
                                        let _ = writeln!(cx.out, "    {}.f_{} = {};", dst, f.name, v);
                                    }
                                }
                            }
                            Some(vi) => {
                                let var = &a.variants()[*vi as usize];
                                let _ = writeln!(cx.out, "    {}.tag = {};", dst, vi);
                                if var.indirect && !var.fields.is_empty() {
                                    let pn = self.struct_name(CItem::Payload(dst_ty, *vi));
                                    self.pending_payloads.push(CItem::Payload(dst_ty, *vi));
                                    let _ = writeln!(cx.out, "    {}.u.v{} = ({}*)nx_alloc(sizeof({}));", dst, vi, pn, pn);
                                    for (i, v) in vals.iter().enumerate() {
                                        let _ = writeln!(cx.out, "    {}.u.v{}->f{} = {};", dst, vi, i, v);
                                    }
                                } else {
                                    for (i, v) in vals.iter().enumerate() {
                                        let _ = writeln!(cx.out, "    {}.u.v{}.f{} = {};", dst, vi, i, v);
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    fn binary(&mut self, op: BinOp, t: Ty, rhs_t: Ty, x: &str, y: &str, span: Span) -> String {
        let tcx = self.tcx();
        let kind = tcx.kind(t);
        match &*kind {
            TyKind::Int(i) => {
                let sfx = int_suffix(*i);
                let ct = int_cty(*i);
                let ut = int_cty(match i {
                    IntTy::I8 => IntTy::U8,
                    IntTy::I16 => IntTy::U16,
                    IntTy::I32 => IntTy::U32,
                    IntTy::I64 => IntTy::U64,
                    IntTy::Isize => IntTy::Usize,
                    other => *other,
                });
                let checked = |g: &mut Self, name: &str| {
                    let loc = g.loc(span);
                    format!("nx_{}_{}({}, {}, {})", name, sfx, x, y, loc)
                };
                match op {
                    BinOp::Add => checked(self, "add"),
                    BinOp::Sub => checked(self, "sub"),
                    BinOp::Mul => checked(self, "mul"),
                    BinOp::Div => checked(self, "div"),
                    BinOp::Rem => checked(self, "rem"),
                    BinOp::AddWrap => format!("({})(({}){} + ({}){})", ct, ut, x, ut, y),
                    BinOp::SubWrap => format!("({})(({}){} - ({}){})", ct, ut, x, ut, y),
                    BinOp::MulWrap => format!("({})(({}){} * ({}){})", ct, ut, x, ut, y),
                    BinOp::BitAnd => format!("({})({} & {})", ct, x, y),
                    BinOp::BitOr => format!("({})({} | {})", ct, x, y),
                    BinOp::BitXor => format!("({})({} ^ {})", ct, x, y),
                    BinOp::Shl | BinOp::Shr => {
                        let loc = self.loc(span);
                        let amount = match tcx.as_int(rhs_t) {
                            Some(r) if !r.signed() => format!("(({}) > (uint64_t)INT64_MAX ? (int64_t)-1 : (int64_t){})", y, y),
                            _ => format!("(int64_t){}", y),
                        };
                        format!("nx_{}_{}({}, {}, {})", if op == BinOp::Shl { "shl" } else { "shr" }, sfx, x, amount, loc)
                    }
                    _ => format!("({} {} {})", x, c_cmp(op), y),
                }
            }
            TyKind::Float(f) => match op {
                BinOp::Rem => {
                    if *f == FloatTy::F32 {
                        format!("fmodf({}, {})", x, y)
                    } else {
                        format!("fmod({}, {})", x, y)
                    }
                }
                BinOp::Add => format!("({} + {})", x, y),
                BinOp::Sub => format!("({} - {})", x, y),
                BinOp::Mul => format!("({} * {})", x, y),
                BinOp::Div => format!("({} / {})", x, y),
                _ => format!("({} {} {})", x, c_cmp(op), y),
            },
            TyKind::Adt(..) => {
                // Fieldless enums: compare tags.
                format!("({}.tag {} {}.tag)", x, c_cmp(op), y)
            }
            TyKind::Unit => (if op == BinOp::Eq { "true" } else { "false" }).into(),
            _ => match op {
                BinOp::And => format!("({} && {})", x, y),
                BinOp::Or => format!("({} || {})", x, y),
                _ => format!("({} {} {})", x, c_cmp(op), y),
            },
        }
    }

    fn cast(&mut self, from: Ty, to: Ty, v: &str, span: Span) -> String {
        let tcx = self.tcx();
        let (kf, kt) = (tcx.kind(from), tcx.kind(to));
        let tc = self.ctype(to);
        match (&*kf, &*kt) {
            (TyKind::Int(a), TyKind::Int(b)) => {
                let (a, b) = (*a, *b);
                let fits = if a.signed() == b.signed() {
                    int_bits(a) <= int_bits(b) && !(matches!(a, IntTy::Isize | IntTy::Usize) && !matches!(b, IntTy::I64 | IntTy::U64 | IntTy::Isize | IntTy::Usize))
                } else {
                    !a.signed() && b.signed() && int_bits(a) < int_bits(b)
                };
                if fits {
                    return format!("({}){}", tc, v);
                }
                let loc = self.loc(span);
                match (a.signed(), b.signed()) {
                    (true, true) => format!("({})nx_cast_ss((int64_t){}, INT64_C({}), INT64_C({}), {})", tc, v, if b.bits() == 64 { "-9223372036854775807-1".to_string() } else { b.min().to_string() }, b.max(), loc),
                    (true, false) => format!("({})nx_cast_su((int64_t){}, UINT64_C({}), {})", tc, v, b.max(), loc),
                    (false, true) => format!("({})nx_cast_us((uint64_t){}, INT64_C({}), {})", tc, v, b.max(), loc),
                    (false, false) => format!("({})nx_cast_uu((uint64_t){}, UINT64_C({}), {})", tc, v, b.max(), loc),
                }
            }
            (TyKind::Int(_), TyKind::Float(_)) => format!("({}){}", tc, v),
            (TyKind::Float(_), TyKind::Float(_)) => format!("({}){}", tc, v),
            (TyKind::Float(_), TyKind::Int(b)) => {
                let loc = self.loc(span);
                if b.signed() {
                    format!("({})nx_cast_fs((double){}, {}, {})", tc, v, b.bits(), loc)
                } else {
                    format!("({})nx_cast_fu((double){}, {}, {})", tc, v, b.bits(), loc)
                }
            }
            (TyKind::Bool, TyKind::Int(_)) => format!("({}){}", tc, v),
            (TyKind::Char, TyKind::Int(b)) => {
                let b = *b;
                if b.bits() >= 32 && !(b == IntTy::I32) {
                    format!("({}){}", tc, v)
                } else {
                    let loc = self.loc(span);
                    if b.signed() {
                        format!("({})nx_cast_us((uint64_t){}, INT64_C({}), {})", tc, v, b.max(), loc)
                    } else {
                        format!("({})nx_cast_uu((uint64_t){}, UINT64_C({}), {})", tc, v, b.max(), loc)
                    }
                }
            }
            (TyKind::Int(a), TyKind::Char) => {
                let loc = self.loc(span);
                if a.signed() {
                    format!("nx_cast_char_s((int64_t){}, {})", v, loc)
                } else {
                    format!("nx_cast_char_u((uint64_t){}, {})", v, loc)
                }
            }
            _ => format!("({}){}", tc, v),
        }
    }

    // -----------------------------------------------------------------------
    // Terminators

    fn emit_term(&mut self, cx: &mut FnCx, b: &BasicBlock) {
        self.line(cx, b.term_span);
        match &b.term {
            Terminator::Goto(t) => {
                let _ = writeln!(cx.out, "    goto bb{};", t);
            }
            Terminator::Switch { discr, targets, otherwise } => {
                let d = self.operand(cx, discr);
                let dt = self.operand_ty(cx, discr);
                if dt == self.tcx().bool && targets.len() == 1 {
                    let (v, t) = targets[0];
                    let _ = writeln!(cx.out, "    if ({}{}) goto bb{}; else goto bb{};", if v == 0 { "!" } else { "" }, d, t, otherwise);
                } else {
                    let _ = writeln!(cx.out, "    switch ({}) {{", d);
                    for (v, t) in targets {
                        let _ = writeln!(cx.out, "    case {}u: goto bb{};", v, t);
                    }
                    let _ = writeln!(cx.out, "    default: goto bb{};\n    }}", otherwise);
                }
            }
            Terminator::Return => {
                if cx.ret_void {
                    let _ = writeln!(cx.out, "    return;");
                } else {
                    let _ = writeln!(cx.out, "    return _0;");
                }
            }
            Terminator::Unreachable => {
                let _ = writeln!(cx.out, "    NX_UNREACHABLE();");
            }
            Terminator::Call { callee, args, dest, target } => {
                self.emit_call(cx, callee, args, dest.as_ref(), b.term_span);
                match target {
                    Some(t) => {
                        let _ = writeln!(cx.out, "    goto bb{};", t);
                    }
                    None => {
                        let _ = writeln!(cx.out, "    NX_UNREACHABLE();");
                    }
                }
            }
        }
    }

    fn assign_result(&mut self, cx: &mut FnCx, dest: Option<&Place>, expr: String, ret_ty: Ty) {
        match dest {
            Some(d) if !self.is_void(ret_ty) => {
                let p = self.place(cx, d);
                let _ = writeln!(cx.out, "    {} = {};", p, expr);
            }
            Some(d) => {
                let p = self.place(cx, d);
                let _ = writeln!(cx.out, "    {};\n    {} = 0;", expr, p);
            }
            None => {
                let _ = writeln!(cx.out, "    {};", expr);
            }
        }
    }

    fn emit_call(&mut self, cx: &mut FnCx, callee: &Callee, args: &[Operand], dest: Option<&Place>, span: Span) {
        let tcx = self.tcx();
        let vals: Vec<String> = args.iter().map(|a| self.operand(cx, a)).collect();
        let arg_tys: Vec<Ty> = args.iter().map(|a| self.operand_ty(cx, a)).collect();
        match callee {
            Callee::Fn(f, targs) => {
                let targs: Vec<Ty> = targs.iter().map(|&t| tcx.subst(t, &cx.targs)).collect();
                let fd = self.p.func(*f);
                let ret = tcx.subst(fd.ret, &targs);
                if let Some(name) = fd.intrinsic() {
                    let name = name.to_string();
                    self.emit_intrinsic(cx, &name, &targs, &vals, &arg_tys, dest, ret, span);
                    return;
                }
                let fname = if fd.is_extern() { self.extern_name(*f) } else { self.instance(*f, targs) };
                let mut vals = vals;
                if fd.track_caller {
                    vals.push(self.loc(span));
                }
                let call = format!("{}({})", fname, vals.join(", "));
                self.assign_result(cx, dest, call, ret);
            }
            Callee::Indirect(fop) => {
                let ft = self.operand_ty(cx, fop);
                let ret = match &*tcx.kind(ft) {
                    TyKind::Fn(_, r) => *r,
                    _ => tcx.unit,
                };
                let fv = self.operand(cx, fop);
                let call = format!("{}({})", fv, vals.join(", "));
                self.assign_result(cx, dest, call, ret);
            }
            Callee::Builtin(_) => unreachable!("builtins are lowered to runtime calls"),
            Callee::Prim(op) => self.emit_prim(cx, *op, &vals, &arg_tys, dest, span),
            Callee::Runtime(rt) => {
                let loc = self.loc(span);
                let (call, ret) = match rt {
                    RtFn::StrEmpty => ("nx_str_empty()".to_string(), self.p.string_ty()),
                    RtFn::StrPushStr => (format!("nx_str_push_str({}, {})", vals[0], vals[1]), tcx.unit),
                    RtFn::StrConcat => (format!("nx_str_concat({}, {})", vals[0], vals[1]), self.p.string_ty()),
                    RtFn::StrEq => (format!("nx_str_eq({}, {})", vals[0], vals[1]), tcx.bool),
                    RtFn::StrCmp => (format!("nx_str_cmp({}, {})", vals[0], vals[1]), tcx.i32),
                    RtFn::StrDecodeChar => (format!("nx_str_decode({}, (size_t*){})", vals[0], vals[1]), tcx.char),
                    RtFn::Print { newline, stderr } => (format!("nx_print({}, {}, {})", vals[0], newline, stderr), tcx.unit),
                    RtFn::PanicStr => (format!("nx_panic_str({}, {})", vals[0], loc), tcx.unit),
                    RtFn::PanicMsg(m) => (format!("nx_panic({}, {})", c_string_literal(m.as_bytes()), loc), tcx.unit),
                    RtFn::Fmt { spec } => {
                        let sp = self.spec(spec);
                        let vt = arg_tys[1];
                        let call = match &*tcx.kind(vt) {
                            TyKind::Int(i) if i.signed() => format!("nx_fmt_i64({}, (int64_t){}, {})", vals[0], vals[1], sp),
                            TyKind::Int(_) => format!("nx_fmt_u64({}, (uint64_t){}, {})", vals[0], vals[1], sp),
                            TyKind::Float(f) => format!("nx_fmt_f64({}, (double){}, {}, {})", vals[0], vals[1], *f == FloatTy::F32, sp),
                            TyKind::Bool => format!("nx_fmt_bool({}, {}, {})", vals[0], vals[1], sp),
                            TyKind::Char => format!("nx_fmt_char({}, {}, {})", vals[0], vals[1], sp),
                            TyKind::Ptr(_) => format!("nx_fmt_str({}, {}, {})", vals[0], vals[1], sp),
                            _ => format!("nx_panic(\"unformattable value\", {})", loc),
                        };
                        (call, tcx.unit)
                    }
                };
                self.assign_result(cx, dest, call, ret);
            }
        }
    }

    fn emit_prim(&mut self, cx: &mut FnCx, op: PrimOp, vals: &[String], tys: &[Ty], dest: Option<&Place>, span: Span) {
        let tcx = self.tcx();
        let recv_ty = tys.first().copied().unwrap_or(tcx.unit);
        let loc = self.loc(span);
        let int = tcx.as_int(recv_ty);
        let float = tcx.as_float(recv_ty);
        let fsuffix = if float == Some(FloatTy::F32) { "f" } else { "" };
        let (expr, ret): (String, Ty) = match op {
            PrimOp::IntAbs => (format!("nx_abs_{}({}, {})", int_suffix(int.unwrap()), vals[0], loc), recv_ty),
            PrimOp::IntMin => (format!("({} < {} ? {} : {})", vals[0], vals[1], vals[0], vals[1]), recv_ty),
            PrimOp::IntMax => (format!("({} > {} ? {} : {})", vals[0], vals[1], vals[0], vals[1]), recv_ty),
            PrimOp::IntPow => (format!("nx_pow_{}({}, {}, {})", int_suffix(int.unwrap()), vals[0], vals[1], loc), recv_ty),
            PrimOp::FloatUnary(name) => {
                let c = match name {
                    "ln" => "log",
                    "abs" => "fabs",
                    other => other,
                };
                (format!("{}{}({})", c, fsuffix, vals[0]), recv_ty)
            }
            PrimOp::FloatBinary(name) => {
                let c = match name {
                    "powf" => "pow",
                    "min" => "fmin",
                    "max" => "fmax",
                    other => other,
                };
                (format!("{}{}({}, {})", c, fsuffix, vals[0], vals[1]), recv_ty)
            }
            PrimOp::FloatIsNan => (format!("(isnan({}) != 0)", vals[0]), tcx.bool),
            PrimOp::FloatIsInfinite => (format!("(isinf({}) != 0)", vals[0]), tcx.bool),
            PrimOp::FloatIsFinite => (format!("(isfinite({}) != 0)", vals[0]), tcx.bool),
            PrimOp::CharPredicate(name) => {
                let c = match name {
                    "is_ascii_digit" => "nx_char_is_ascii_digit",
                    "is_ascii_alphabetic" => "nx_char_is_ascii_alphabetic",
                    "is_ascii_alphanumeric" => "nx_char_is_ascii_alphanumeric",
                    "is_whitespace" => "nx_char_is_whitespace",
                    "is_ascii_uppercase" => "nx_char_is_ascii_uppercase",
                    "is_ascii_lowercase" => "nx_char_is_ascii_lowercase",
                    _ => "nx_char_is_ascii",
                };
                (format!("{}({})", c, vals[0]), tcx.bool)
            }
            PrimOp::CharToUpper => (format!("nx_char_to_upper({})", vals[0]), tcx.char),
            PrimOp::CharToLower => (format!("nx_char_to_lower({})", vals[0]), tcx.char),
            PrimOp::CharLenUtf8 => (format!("(uintptr_t)nx_char_len_utf8({})", vals[0]), tcx.usize),
            PrimOp::ToString => {
                let e = match &*tcx.kind(recv_ty) {
                    TyKind::Int(i) if i.signed() => format!("nx_to_string_i64((int64_t){})", vals[0]),
                    TyKind::Int(_) => format!("nx_to_string_u64((uint64_t){})", vals[0]),
                    TyKind::Float(f) => format!("nx_to_string_f64((double){}, {})", vals[0], *f == FloatTy::F32),
                    TyKind::Bool => format!("nx_to_string_bool({})", vals[0]),
                    TyKind::Char => format!("nx_to_string_char({})", vals[0]),
                    _ => "nx_str_empty()".into(),
                };
                (e, self.p.string_ty())
            }
            PrimOp::PtrNull => {
                let t = dest.map(|d| self.place_ty(cx, d)).unwrap_or(tcx.unit);
                let ct = self.ctype(t);
                (format!("(({})0)", ct), t)
            }
            PrimOp::PtrIsNull => (format!("({} == 0)", vals[0]), tcx.bool),
            PrimOp::PtrAddr => (format!("(uintptr_t){}", vals[0]), tcx.usize),
            PrimOp::PtrOffset => (format!("({} + {})", vals[0], vals[1]), recv_ty),
            PrimOp::PtrRead => {
                let elem = match &*tcx.kind(recv_ty) {
                    TyKind::Ptr(e) => *e,
                    _ => tcx.unit,
                };
                (format!("(*{})", vals[0]), elem)
            }
            PrimOp::PtrWrite => (format!("*{} = {}", vals[0], vals[1]), tcx.unit),
            PrimOp::PtrCast => {
                let t = dest.map(|d| self.place_ty(cx, d)).unwrap_or(tcx.unit);
                let ct = self.ctype(t);
                (format!("(({}){})", ct, vals[0]), t)
            }
        };
        self.assign_result(cx, dest, expr, ret);
    }

    #[allow(clippy::too_many_arguments)]
    fn emit_intrinsic(&mut self, cx: &mut FnCx, name: &str, targs: &[Ty], vals: &[String], _tys: &[Ty], dest: Option<&Place>, ret: Ty, span: Span) {
        let tcx = self.tcx();
        let t0 = targs.first().map(|&t| self.ctype(t));
        let expr = match name {
            "size_of" => format!("(uintptr_t)sizeof({})", t0.unwrap()),
            "align_of" => format!("(uintptr_t)_Alignof({})", t0.unwrap()),
            "alloc" => format!("(uint8_t*)nx_alloc({})", vals[0]),
            "realloc" => format!("(uint8_t*)nx_realloc({}, {})", vals[0], vals[1]),
            "free" => format!("nx_free({})", vals[0]),
            "copy" => format!("memmove({}, {}, (size_t){} * sizeof({}))", vals[1], vals[0], vals[2], t0.unwrap()),
            "drop_in_place" => match self.drop_fn(targs[0]) {
                Some(d) => format!("{}({})", d, vals[0]),
                None => "(void)0".into(),
            },
            "forget" => "(void)0".into(),
            "swap" => {
                let ct = t0.unwrap();
                format!("do {{ {} nx_tmp = *{}; *{} = *{}; *{} = nx_tmp; }} while (0)", ct, vals[0], vals[0], vals[1], vals[1])
            }
            "replace" => {
                let p = dest.map(|d| self.place(cx, d));
                match p {
                    Some(p) => {
                        let _ = writeln!(cx.out, "    {} = *{};\n    *{} = {};", p, vals[0], vals[0], vals[1]);
                    }
                    None => {
                        if let Some(d) = self.drop_fn(targs[0]) {
                            let _ = writeln!(cx.out, "    {}({});", d, vals[0]);
                        }
                        let _ = writeln!(cx.out, "    *{} = {};", vals[0], vals[1]);
                    }
                }
                return;
            }
            "rt_read_line" => format!("nx_read_line({})", vals[0]),
            "rt_read_file" => format!("nx_read_file({}, {})", vals[0], vals[1]),
            "rt_write_file" => format!("nx_write_file({}, {}, {})", vals[0], vals[1], vals[2]),
            "flush" => "nx_flush()".into(),
            "rt_arg_count" => "nx_arg_count()".into(),
            "rt_arg" => format!("nx_arg({})", vals[0]),
            "exit" => format!("nx_exit({})", vals[0]),
            "rt_env" => format!("nx_env({}, {})", vals[0], vals[1]),
            "monotonic_ns" => "nx_monotonic_ns()".into(),
            "rt_decode" => format!("nx_str_decode({}, (size_t*){})", vals[0], vals[1]),
            "rt_parse_float" => format!("nx_parse_float({}, {})", vals[0], vals[1]),
            "rt_utf8_valid" => format!("nx_utf8_valid({}, (size_t){})", vals[0], vals[1]),
            "rt_index_fail" => {
                let loc = self.loc(span);
                format!("nx_panic_2u(\"index out of bounds: the index is \", (uint64_t){}, \" but the length is \", (uint64_t){}, {})", vals[0], vals[1], loc)
            }
            other => {
                let loc = self.loc(span);
                format!("nx_panic(\"unknown intrinsic {}\", {})", other, loc)
            }
        };
        let _ = tcx;
        self.assign_result(cx, dest, expr, ret);
    }
}

struct FnCx {
    targs: Vec<Ty>,
    local_tys: Vec<Ty>,
    out: String,
    last_line: Option<(usize, String)>,
    ret_void: bool,
}

fn c_cmp(op: BinOp) -> &'static str {
    match op {
        BinOp::Eq => "==",
        BinOp::Ne => "!=",
        BinOp::Lt => "<",
        BinOp::Le => "<=",
        BinOp::Gt => ">",
        BinOp::Ge => ">=",
        BinOp::And => "&&",
        BinOp::Or => "||",
        BinOp::BitAnd => "&",
        BinOp::BitOr => "|",
        BinOp::BitXor => "^",
        _ => "?",
    }
}

fn int_literal(n: i128, i: IntTy) -> String {
    let ct = int_cty(i);
    if i.signed() {
        if n == i64::MIN as i128 {
            format!("(({})INT64_MIN)", ct)
        } else {
            format!("(({})INT64_C({}))", ct, n)
        }
    } else {
        format!("(({})UINT64_C({}))", ct, n as u128 as u64)
    }
}

fn float_literal(x: f64, f: FloatTy) -> String {
    let s = if x.is_nan() {
        "NAN".to_string()
    } else if x.is_infinite() {
        if x > 0.0 { "INFINITY".to_string() } else { "(-INFINITY)".to_string() }
    } else {
        let s = format!("{:?}", x);
        if s.contains('.') || s.contains('e') || s.contains("inf") { s } else { format!("{}.0", s) }
    };
    match f {
        FloatTy::F32 => format!("((float){})", s),
        FloatTy::F64 => format!("({})", s),
    }
}

#[allow(dead_code)]
fn conv_ref(c: Convention) -> bool {
    c != Convention::Owned
}
